const fs = require('fs');
const path = require('path');

const brandsRoot = path.resolve(__dirname, '../brands');
const ICON_EXTENSION = '.png';
// Exclude the files with the scale suffixes (e.g. "@2x"). React Native resolves them automatically.
const SCALE_SUFFIX_PATTERN = /@\d+(\.\d+)?x$/;
const HEADER = '// Autogenerated, do not edit. Run "node scripts/generate-icon-source-map.js"';

const sourceMaps = [
	{
		folder: 'assets/images/icons',
		fileName: 'icon-source-map.js',
		exportName: 'iconSourceMap'
	},
	{
		folder: 'assets/images/tokens',
		fileName: 'token-image-source-map.js',
		exportName: 'tokenImageSourceMap'
	}
];

const getSubfolderNames = folderPath => fs.readdirSync(folderPath, { withFileTypes: true })
	.filter(entry => entry.isDirectory())
	.map(entry => entry.name)
	.sort();


const getIconNames = folderPath => fs.readdirSync(folderPath)
	.filter(fileName => path.extname(fileName) === ICON_EXTENSION)
	.map(fileName => path.basename(fileName, ICON_EXTENSION))
	.filter(name => !SCALE_SUFFIX_PATTERN.test(name))
	.sort();


const readIconTree = (folderPath, relativePath = '') => Object.fromEntries([
	...getIconNames(folderPath).map(name => [name, `${relativePath}${name}${ICON_EXTENSION}`]),
	...getSubfolderNames(folderPath).map(folderName =>
		[folderName, readIconTree(path.join(folderPath, folderName), `${relativePath}${folderName}/`)])
]);

const createEntries = (iconTree, depth) => {
	const indent = '\t'.repeat(depth);

	return Object.entries(iconTree)
		.map(([name, value]) => typeof value === 'string'
			? `${indent}'${name}': require('./${value}')`
			: `${indent}'${name}': {\n${createEntries(value, depth + 1)}\n${indent}}`)
		.join(',\n');
};

const createSourceMapModule = (iconTree, exportName) =>
	`${HEADER}\nexport const ${exportName} = {\n${createEntries(iconTree, 1)}\n};\n`;

const brands = getSubfolderNames(brandsRoot);

sourceMaps.forEach(({ folder, fileName, exportName }) => {
	brands.forEach(brand => {
		const folderPath = path.join(brandsRoot, brand, folder);
		const outputPath = path.join(folderPath, fileName);

		fs.writeFileSync(outputPath, createSourceMapModule(readIconTree(folderPath), exportName));
		process.stdout.write(`${brand}: ${path.relative(process.cwd(), outputPath)}\n`);
	});
});
