const fs = require('fs');
const path = require('path');

const brandsRoot = path.resolve(__dirname, '../brands');
const ICONS_PATH = 'assets/images/icons';
const OUTPUT_FILE_NAME = 'icon-source-map.js';
const ICON_EXTENSION = '.png';
// Exclude the files with the scale suffixes (e.g. "@2x"). React Native resolves them automatically. 
const SCALE_SUFFIX_PATTERN = /@\d+(\.\d+)?x$/;
const HEADER = '// Autogenerated, do not edit. Run "node scripts/generate-icon-source-map.js"';

const getSubfolderNames = folderPath => fs.readdirSync(folderPath, { withFileTypes: true })
	.filter(entry => entry.isDirectory())
	.map(entry => entry.name)
	.sort();


const getIconNames = folderPath => fs.readdirSync(folderPath)
	.filter(fileName => path.extname(fileName) === ICON_EXTENSION)
	.map(fileName => path.basename(fileName, ICON_EXTENSION))
	.filter(name => !SCALE_SUFFIX_PATTERN.test(name))
	.sort();


const createSourceMapModule = iconsPath => {
	const folderEntries = getSubfolderNames(iconsPath).map(folderName => {
		const iconEntries = getIconNames(path.join(iconsPath, folderName))
			.map(name => `\t\t'${name}': require('./${folderName}/${name}${ICON_EXTENSION}')`);

		return `\t'${folderName}': {\n${iconEntries.join(',\n')}\n\t}`;
	});

	return `${HEADER}\nexport const iconSourceMap = {\n${folderEntries.join(',\n')}\n};\n`;
};

getSubfolderNames(brandsRoot).forEach(brand => {
	const iconsPath = path.join(brandsRoot, brand, ICONS_PATH);
	const outputPath = path.join(iconsPath, OUTPUT_FILE_NAME);

	fs.writeFileSync(outputPath, createSourceMapModule(iconsPath));
	process.stdout.write(`${brand}: ${path.relative(process.cwd(), outputPath)}\n`);
});
